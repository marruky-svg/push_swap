#include "libft.h"

static int	is_in(char c, char const *set)
{
	while (*set)
	{
		if (*set == c)
			return (1);
		set++;
	}
	return (0);
}

char	*ft_strtrim(char const *s1, char const *set)
{
	size_t	start;
	size_t	end;
	size_t	len;

	start = 0;
	end = ft_strlen(s1);
	while (is_in(s1[start], set))
		start++;
	while (end > start && is_in(s1[end - 1], set))
		end--;
	len = end - start;
	return (ft_substr(s1, start, len));
}
